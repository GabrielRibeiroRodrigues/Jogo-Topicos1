# Legenda:
#   #  → parede
#   .  → chão (vazio)
#   B  → caixa (obstáculo + esconderijo)
#   I  → intel (objetivo obrigatório)
#   E  → saída (objetivo)
#
# Fases contínuas horizontais (largura > tela) para rolagem estilo side-scroller.


def _parede(largura):
    return "#" * largura


def _linha(largura, blocos=None, itens=None):
    row = ["#"] + ["."] * (largura - 2) + ["#"]
    for inicio, fim, char in (blocos or []):
        for col in range(max(1, inicio), min(largura - 1, fim)):
            row[col] = char
    for col, char in (itens or []):
        if 0 < col < largura - 1:
            row[col] = char
    return "".join(row)


